"""TFN: the table functions (VOP 0x20..0x29, docs/isa.md "Table functions").

One pipelined unit evaluates every activation the models need (sigmoid, SiLU, tanh, GELU in
both forms, softplus, Mish, QuickGELU, sin, cos) as a piecewise quadratic in fp32: the input is
mapped onto 256 unit segments, `u = x * S + O`, segment `s = trunc(u)`, `f = u - s` (exact), and
`g = (c2[s] * f + c1[s]) * f + c0[s]` (rounded mul then add each step, the composites' units);
outside the segments a constant tail. A post step gives `x * g` (SiLU, GELU, ...), `g + relu(x)`
(softplus) or `g`. The tables (rtl/vpu/otpu_tfn_rom.sv, generated by tools/gen_tfn_tables.py)
ARE the definition: the ISA simulator and the RTL read the same fp32 words.

The hardware runs TFN on the stream engine's composite loop (otpu_se_comp): five ops in two
passes, LANES/2 columns a cycle like RECIP, against 5-8 VOPs for the exp2/recip chains.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass

import numpy as np

from . import fp32 as F

NSEG = 256
V_TFN0 = 0x20                    # VOP func of table function 0
POST_NONE, POST_MUL, POST_ADDRELU = 0, 1, 2


@dataclass(frozen=True)
class Desc:
    name: str
    table: int                   # 0..7
    S: float                     # u = |x| or x, times S, plus O (fp32 constants)
    O: float
    post: int
    periodic: bool = False       # u = |x| S + O, the segment is trunc(u) mod 256, no tails
    odd: bool = False            # periodic: the result takes x's sign (sin)


SIN_S = float(np.float32(NSEG / (2.0 * np.pi)))

# fn = func - 0x20
FUNCS = [
    Desc("sigmoid", 0, 8.0, 128.0, POST_NONE),
    Desc("silu", 0, 8.0, 128.0, POST_MUL),
    Desc("tanh", 1, 16.0, 128.0, POST_NONE),
    Desc("gelu", 2, 16.0, 128.0, POST_MUL),           # x Phi(x), the erf form
    Desc("gelu_tanh", 3, 16.0, 128.0, POST_MUL),      # x sigmoid(2 sqrt(2/pi) (x + 0.044715 x^3))
    Desc("softplus", 4, 4.0, 128.0, POST_ADDRELU),    # log1p(exp(-|x|)) + max(x, 0)
    Desc("mish", 5, 8.0, 128.0, POST_MUL),            # x tanh(softplus(x))
    Desc("quick_gelu", 6, 8.0, 128.0, POST_MUL),      # x sigmoid(1.702 x)
    Desc("sin", 7, SIN_S, 0.0, POST_NONE, periodic=True, odd=True),
    Desc("cos", 7, SIN_S, 64.0, POST_NONE, periodic=True),
]
BY_NAME = {d.name: i for i, d in enumerate(FUNCS)}
NFUNC = len(FUNCS)


def func_code(name: str) -> int:
    return V_TFN0 + BY_NAME[name]


def is_tfn(func: int) -> bool:
    return V_TFN0 <= func < V_TFN0 + NFUNC


# ---------------------------------------------------------------- the reference functions
def _erf(x):
    from math import erf
    return np.vectorize(erf)(x)


def _sig(x):
    return 1.0 / (1.0 + np.exp(-x))


def _softplus(x):
    return np.logaddexp(0.0, x)


# the function each table holds, of x (float64), and its tails (x below / above the segments)
TABLES = [
    ("sigmoid", _sig, 0.0, 1.0),
    ("tanh", np.tanh, -1.0, 1.0),
    ("phi", lambda x: 0.5 * (1.0 + _erf(x / np.sqrt(2.0))), 0.0, 1.0),
    ("gelu_tanh_g", lambda x: _sig(2.0 * np.sqrt(2.0 / np.pi) * (x + 0.044715 * x ** 3)), 0.0, 1.0),
    ("softplus_r", lambda x: np.log1p(np.exp(-np.abs(x))), 0.0, 0.0),
    ("mish_g", lambda x: np.tanh(_softplus(x)), 0.0, 1.0),
    ("quick_gelu_g", lambda x: _sig(1.702 * x), 0.0, 1.0),
    ("sin", lambda x: np.sin(x), 0.0, 0.0),
]
_TABLE_DESC = {0: FUNCS[0], 1: FUNCS[2], 2: FUNCS[3], 3: FUNCS[4], 4: FUNCS[5], 5: FUNCS[6],
               6: FUNCS[7], 7: FUNCS[8]}


def truth(name: str, x):
    """The exact function in float64 (for accuracy checks)."""
    x = np.asarray(x, np.float64)
    if name == "sigmoid":
        return _sig(x)
    if name == "silu":
        return x * _sig(x)
    if name == "tanh":
        return np.tanh(x)
    if name == "gelu":
        return x * 0.5 * (1.0 + _erf(x / np.sqrt(2.0)))
    if name == "gelu_tanh":
        return 0.5 * x * (1.0 + np.tanh(np.sqrt(2.0 / np.pi) * (x + 0.044715 * x ** 3)))
    if name == "softplus":
        return _softplus(x)
    if name == "mish":
        return x * np.tanh(_softplus(x))
    if name == "quick_gelu":
        return x * _sig(1.702 * x)
    if name == "sin":
        return np.sin(x)
    if name == "cos":
        return np.cos(x)
    raise KeyError(name)


def fit_tables():
    """The coefficients (float64 interpolation at each segment's ends and middle, rounded to
    fp32: the pieces meet at the knots, c0 is the function at the knot, so sigmoid(0) = 0.5 and
    sin(0) = 0 exactly) and tails: (coef uint32 [8, 256, 3] as c2, c1, c0; tails uint32 [8, 2])."""
    t = np.array([0.0, 0.5, 1.0])                                       # nodes in [0, 1]
    V = np.stack([t ** 2, t, np.ones(3)], axis=1)
    coef = np.zeros((8, NSEG, 3), np.uint32)
    tails = np.zeros((8, 2), np.uint32)
    for k, (_, fn, lo, hi) in enumerate(TABLES):
        d = _TABLE_DESC[k]
        s = np.arange(NSEG)[:, None] + t[None, :]                        # u
        x = (s - d.O) / d.S if not d.periodic else s * (2.0 * np.pi / NSEG)
        y = fn(x)
        c = np.linalg.solve(V[None], y[..., None])[..., 0]               # [NSEG, 3]
        coef[k] = c.astype(np.float32).view(np.uint32)
        tails[k] = np.array([lo, hi], np.float32).view(np.uint32)
    return coef, tails


# ---------------------------------------------------------------- the table file
ROM_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "rtl", "vpu", "otpu_tfn_rom.sv")
_tabs = None


def tables():
    """(coef uint32 [8, 256, 3], tails uint32 [8, 2]) as the RTL's ROM holds them."""
    global _tabs
    if _tabs is None:
        try:
            src = open(ROM_FILE).read()
        except OSError:
            _tabs = fit_tables()
            return _tabs
        words = [int(w, 16) for w in re.findall(r"96'h([0-9a-fA-F_]+)", src)
                 for w in [w.replace("_", "")]]
        tline = re.search(r"TFN_TAIL \[16\] = (.*);", src).group(1)
        tl = [int(w, 16) for w in re.findall(r"32'h([0-9a-fA-F]{8})", tline)]
        coef = np.zeros((8, NSEG, 3), np.uint32)
        for i, w in enumerate(words):
            coef[i // NSEG, i % NSEG] = [(w >> 64) & 0xFFFFFFFF, (w >> 32) & 0xFFFFFFFF,
                                         w & 0xFFFFFFFF]
        _tabs = (coef, np.array(tl, np.uint32).reshape(8, 2))
    return _tabs


def rom_sv(coef, tails) -> str:
    lines = ["// Generated by tools/gen_tfn_tables.py: the TFN tables (opentpu/tfn.py, docs/isa.md",
             "// \"Table functions\"). Entry {table, segment}: {c2, c1, c0} fp32; tails {lo, hi}.",
             "// This file is the definition: the ISA simulator reads these words too.",
             "package otpu_tfn_rom;",
             f"  localparam logic [95:0] TFN_COEF [{8 * NSEG}] = '{{"]
    ent = []
    for k in range(8):
        for s in range(NSEG):
            c2, c1, c0 = (int(v) for v in coef[k, s])
            ent.append(f"96'h{c2:08x}_{c1:08x}_{c0:08x}")
    for i in range(0, len(ent), 4):
        lines.append("    " + ", ".join(ent[i:i + 4]) + ("," if i + 4 < len(ent) else ""))
    lines.append("  };")
    tl = ", ".join(f"32'h{int(v):08x}" for v in tails.reshape(-1))
    lines.append(f"  localparam logic [31:0] TFN_TAIL [16] = '{{{tl}}};")
    lines.append("  // the functions (fn = VOP func - 0x20): table, S, O, post (0 g, 1 x*g, 2 g + relu(x)),")
    lines.append("  // periodic, odd")
    lines.append(f"  localparam int TFN_N = {NFUNC};")
    lines.append("  typedef struct packed {")
    lines.append("    logic [2:0] tbl; logic [31:0] s, o; logic [1:0] post; logic per, odd;")
    lines.append("  } tfn_d_t;")
    lines.append("  function automatic tfn_d_t tfn_desc(input logic [3:0] fn);")
    lines.append("    case (fn)")
    for i, d in enumerate(FUNCS):
        sb = int(np.float32(d.S).view(np.uint32)); ob = int(np.float32(d.O).view(np.uint32))
        lines.append(f"      4'd{i}: return '{{tbl: 3'd{d.table}, s: 32'h{sb:08x}, o: 32'h{ob:08x}, "
                     f"post: 2'd{d.post}, per: 1'b{int(d.periodic)}, odd: 1'b{int(d.odd)}}};"
                     f"  // {d.name}")
    lines.append("      default: return '0;")
    lines.append("    endcase")
    lines.append("  endfunction")
    lines.append("endpackage")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- the bit-exact model
def _trunc(u):
    """u >= 0 (flushed, finite): its integer part as fp32 bits, and the integer mod 256."""
    b = F.bits(u).astype(np.int64)
    e = (b >> 23) & 0xFF
    m = (b & 0x7FFFFF) | 0x800000
    small = e < 127
    sh = np.clip(150 - e, 0, 23)
    tb = np.where(small, 0, np.where(e >= 150, b, b & ~((1 << sh) - 1)))
    ip = np.where(e >= 150, (m << np.clip(e - 150, 0, 8)), m >> np.clip(150 - e, 0, 24))
    ip = np.where(small, 0, np.where(e - 150 >= 8, 0, ip)) & (NSEG - 1)
    return F.from_bits(tb.astype(np.uint32)), ip.astype(np.int64)


def tfn(fn: int, x):
    """Table function fn (0..9) of x, bit for bit as the hardware computes it."""
    d = FUNCS[fn]
    coef, tails = tables()
    x = F.ftz(np.asarray(x, np.float32))
    a = F.fabs(x) if d.periodic else x
    u = F.add(F.mul(a, np.float32(d.S)), np.float32(d.O))
    ub = F.bits(u)
    if d.periodic:
        bad = ((ub >> 23) & 0xFF) == 0xFF
        lo = hi = np.zeros(u.shape, bool)
    else:
        bad = np.zeros(u.shape, bool)
        lo = F.gt(np.float32(0.0), u)
        hi = ~F.gt(np.float32(NSEG), u)
    tail = lo | hi | bad
    uu = np.where(tail, np.float32(0.0), u).astype(np.float32)
    t, seg = _trunc(uu)
    f = F.add(uu, F.from_bits(F.bits(t) ^ np.uint32(0x80000000)))
    c = coef[d.table][seg]                                              # [..., 3]
    tv = np.where(hi, tails[d.table, 1], tails[d.table, 0])
    c2 = np.where(lo | hi, np.uint32(0), c[..., 0])
    c1 = np.where(lo | hi, np.uint32(0), c[..., 1])
    c0 = np.where(lo | hi, tv, c[..., 2])
    g = F.add(F.mul(F.from_bits(c2), f), F.from_bits(c1))
    g = F.add(F.mul(g, f), F.from_bits(c0))
    if d.post == POST_MUL:
        g = F.add(F.mul(g, x), F.from_bits(np.uint32(0x80000000)))
    elif d.post == POST_ADDRELU:
        r = np.where(F.gt(x, np.float32(0.0)), x, np.float32(0.0)).astype(np.float32)
        g = F.add(F.mul(g, np.float32(1.0)), r)
    else:
        g = F.add(F.mul(g, np.float32(1.0)), F.from_bits(np.uint32(0x80000000)))
    if d.odd:
        neg = (F.bits(x) >> 31).astype(bool)
        g = np.where(neg, F.from_bits(F.bits(g) ^ np.uint32(0x80000000)), g)
    g = np.where(bad, F.from_bits(np.uint32(0x7FC00000)), g)
    return np.asarray(g, np.float32)
